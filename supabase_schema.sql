-- Enable pgcrypto extension for UUIDs and hashing if needed
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- -------------------------------------------------------------
-- 1. Users Table (Authentication & User Profiles)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    avatar_color TEXT DEFAULT '#059669',
    google_id TEXT DEFAULT NULL,
    profile_picture TEXT DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- -------------------------------------------------------------
-- 2. Generated Recipes Table (Full CRUD Support)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.generated_recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    category TEXT DEFAULT 'Everyday Meal',
    prep_time TEXT DEFAULT '15 mins',
    cook_time TEXT DEFAULT '20 mins',
    difficulty TEXT DEFAULT 'Easy',
    calories TEXT DEFAULT '320 kcal',
    ingredients JSONB DEFAULT '[]'::jsonb,
    instructions JSONB DEFAULT '[]'::jsonb,
    nutrition JSONB DEFAULT '{}'::jsonb,
    tips TEXT DEFAULT '',
    substitutes TEXT DEFAULT '',
    language TEXT DEFAULT 'en',
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- -------------------------------------------------------------
-- 3. Favourites Table (User Bookmarked Recipes)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.favourites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    category TEXT DEFAULT 'General',
    prep_time TEXT DEFAULT '15 mins',
    cook_time TEXT DEFAULT '25 mins',
    difficulty TEXT DEFAULT 'Medium',
    calories TEXT DEFAULT '350 kcal',
    ingredients JSONB DEFAULT '[]'::jsonb,
    instructions JSONB DEFAULT '[]'::jsonb,
    nutrition JSONB DEFAULT '{}'::jsonb,
    tips TEXT DEFAULT '',
    substitutes TEXT DEFAULT '',
    language TEXT DEFAULT 'en',
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- -------------------------------------------------------------
-- 4. High-Performance Query Indexes
-- -------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(LOWER(email));
CREATE INDEX IF NOT EXISTS idx_recipes_user_id ON public.generated_recipes(user_id);
CREATE INDEX IF NOT EXISTS idx_recipes_created_at ON public.generated_recipes(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_favourites_user_id ON public.favourites(user_id);
CREATE INDEX IF NOT EXISTS idx_favourites_title ON public.favourites(title);

-- -------------------------------------------------------------
-- 5. Row Level Security (RLS) & Access Policies
-- -------------------------------------------------------------
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.generated_recipes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favourites ENABLE ROW LEVEL SECURITY;

-- Allow Flask Backend Full Access using Anon/Service-Role Key
GRANT ALL ON TABLE public.users TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.generated_recipes TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.favourites TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

DO $$
BEGIN
    DROP POLICY IF EXISTS "Backend Full Access Users" ON public.users;
    CREATE POLICY "Backend Full Access Users" ON public.users FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Backend Full Access Recipes" ON public.generated_recipes;
    CREATE POLICY "Backend Full Access Recipes" ON public.generated_recipes FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Backend Full Access Favourites" ON public.favourites;
    CREATE POLICY "Backend Full Access Favourites" ON public.favourites FOR ALL USING (true) WITH CHECK (true);
END $$;
